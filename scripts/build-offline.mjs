import { createHash } from 'node:crypto';
import { readdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

// Run after Vite and source packaging. Large source archives stay downloadable,
// but are never fetched automatically by the offline application.
const directory = fileURLToPath(new URL('../dist/', import.meta.url));
async function filesIn(directory, prefix = '') {
  const files = [];
  for (const entry of await readdir(directory, { withFileTypes: true })) {
    const name = path.posix.join(prefix, entry.name);
    if (entry.isDirectory() && name !== 'source') files.push(...await filesIn(path.join(directory, entry.name), name));
    else if (entry.isFile() && name !== 'sw.js' && !name.endsWith('.map') && !/\.(?:tgz|tar\.gz|zip)$/.test(name)) files.push(name);
  }
  return files.sort();
}

const files = await filesIn(directory);
if (!files.includes('index.html')) throw new Error('Lancez vite build avant build-offline.mjs.');
const hash = createHash('sha256');
for (const file of files) hash.update(file).update(await readFile(path.join(directory, file)));
const version = hash.digest('hex').slice(0, 16);
const relativeFiles = ['', ...files.map((file) => file.split('/').map(encodeURIComponent).join('/'))];

const source = `// Generated by scripts/build-offline.mjs. Do not edit this file.
const ROOT = new URL('./', self.location.href).pathname;
const PREFIX = 'chansonade:' + encodeURIComponent(ROOT) + ':';
const CACHE = PREFIX + ${JSON.stringify(version)};
const FILES = ${JSON.stringify(relativeFiles)}.map((file) => ROOT + file);
const INDEX = ROOT + 'index.html';

self.addEventListener('install', (event) => {
  event.waitUntil((async () => {
    const cache = await caches.open(CACHE);
    await cache.addAll(FILES);
    // An update waits for the previous tabs to close, preserving an active take.
  })());
});

self.addEventListener('activate', (event) => {
  event.waitUntil((async () => {
    const names = await caches.keys();
    await Promise.all(names.filter((name) => name.startsWith(PREFIX) && name !== CACHE).map((name) => caches.delete(name)));
    await self.clients.claim();
  })());
});

self.addEventListener('fetch', (event) => {
  const request = event.request;
  const url = new URL(request.url);
  // Only the explicitly precached application files belong to this worker.
  // Accounts, changes, source downloads and other nafis.io projects bypass it.
  if (request.method !== 'GET' || url.origin !== self.location.origin || url.pathname.startsWith(ROOT + 'api/') || !FILES.includes(url.pathname)) return;

  event.respondWith((async () => {
    const cache = await caches.open(CACHE);
    const cached = await cache.match(url.pathname, { ignoreVary: true });
    if (cached) return cached;
    try { return await fetch(request); }
    catch { return (request.mode === 'navigate' && await cache.match(INDEX)) || Response.error(); }
  })());
});
`;

await writeFile(path.join(directory, 'sw.js'), source);
console.log(`Hors ligne prêt : ${files.length} fichiers, version ${version}, cache limité au chemin de l’application.`);
